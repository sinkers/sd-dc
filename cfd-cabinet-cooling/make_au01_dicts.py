    def build(self):
        warn, cols = self.checks()
        extract_roof(os.path.join(self.tri, 'room_shell.stl'),
                     os.path.join(self.tri, 'roof.stl'))
        self._extra = self.extra_stls()
        self._gantry_file, self._raised = self.raise_cross_heads()
        self.write('system/blockMeshDict', self.blockMeshDict())
        self.write('system/fvSchemes', self.fvSchemes())
        self.write('system/fvSolution', self.fvSolution())
        self.write('system/snappyHexMeshDict', self.snappyHexMeshDict())
        self.write('system/topoSetDict.patches', self.topoSetDict_patches())
        self.write('system/createPatchDict', self.createPatchDict())
        self.write('system/topoSetDict.baffles', self.topoSetDict_baffles())
        self.write('system/createBafflesDict', self.createBafflesDict())
        self.write('system/topoSetDict.racks', self.topoSetDict_racks())
        self.write('system/fvOptions', self.fvOptions())
        self.write('system/au01Functions', self.functions())
        self.write('system/controlDict', self.controlDict())
        self.write('system/decomposeParDict', self.decomposeParDict())
        self.write('system/slices', self.slices())
        for name, text in self.fields().items():
            self.write(os.path.join('0.orig', name), text)
        return self.report(warn, cols)


