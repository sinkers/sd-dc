#!/usr/bin/env python3
"""
Build the AU01 whitespace OpenFOAM case from the FreeCAD Rev E CFD export.

The point of this generator is that geometry is *read*, not transcribed:
every plane, extent and rack load comes from cfd_export_params.json and the
STL files themselves, both copied verbatim out of the CAD model. Only
solver-side choices live in system/au01Parameters.

    ./make_au01_dicts.py case-au01
"""

import json
import math
import os
import sys
from collections import OrderedDict

CP = 1005.0          # J/kg/K, matches constant/thermophysicalProperties
R_AIR = 287.05
P_ATM = 101325.0


# --------------------------------------------------------------------------
# inputs
# --------------------------------------------------------------------------

def read_params(path):
    """Parse the plain key/value parameter file, ignoring # comments."""
    out = {}
    with open(path) as fh:
        for line in fh:
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            bits = line.split(None, 1)
            if len(bits) == 2:
                out[bits[0]] = bits[1].strip()
    return out


def stl_solids(path):
    """Return OrderedDict name -> (xmin,xmax,ymin,ymax,zmin,zmax)."""
    solids = OrderedDict()
    name = None
    with open(path, errors='replace') as fh:
        for line in fh:
            s = line.strip()
            if s.startswith('solid'):
                name = s[5:].strip() or 'solid%d' % len(solids)
                solids[name] = [1e30, -1e30, 1e30, -1e30, 1e30, -1e30]
            elif s.startswith('vertex') and name is not None:
                p = [float(v) for v in s.split()[1:4]]
                b = solids[name]
                for i in range(3):
                    b[2 * i] = min(b[2 * i], p[i])
                    b[2 * i + 1] = max(b[2 * i + 1], p[i])
    return solids


def extract_roof(src, dst):
    """Write only the roof solids of room_shell.stl to their own file.

    The vertical walls and the floor coincide exactly with blockMesh faces, so
    handing them to snappyHexMesh only invites coincident-surface trouble. The
    gable is the one part of the shell the background mesh cannot represent.
    """
    keep, out, name = False, [], None
    with open(src, errors='replace') as fh:
        for line in fh:
            s = line.strip()
            if s.startswith('solid'):
                name = s[5:].strip()
                keep = 'roof' in name
            if keep:
                out.append(line)
            if s.startswith('endsolid'):
                keep = False
    if not out:
        raise SystemExit('no roof solids found in %s' % src)
    with open(dst, 'w') as fh:
        fh.writelines(out)


# --------------------------------------------------------------------------

def box_solid(name, x0, x1, y0, y1, z0, z1):
    """One axis-aligned box as an ASCII STL solid."""
    v = [(x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0),
         (x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)]
    quads = [((0, 3, 2, 1), (0, 0, -1)), ((4, 5, 6, 7), (0, 0, 1)),
             ((0, 1, 5, 4), (0, -1, 0)), ((3, 7, 6, 2), (0, 1, 0)),
             ((0, 4, 7, 3), (-1, 0, 0)), ((1, 2, 6, 5), (1, 0, 0))]
    out = ['solid %s\n' % name]
    for idx, n in quads:
        for tri in ((idx[0], idx[1], idx[2]), (idx[0], idx[2], idx[3])):
            out.append('  facet normal %g %g %g\n    outer loop\n' % n)
            for i in tri:
                out.append('      vertex %.6f %.6f %.6f\n' % v[i])
            out.append('    endloop\n  endfacet\n')
    out.append('endsolid %s\n' % name)
    return ''.join(out)


HEADER = ('// GENERATED by make_au01_dicts.py - do not edit.\n'
          '// Geometry comes from system/cfd_export_params.json and\n'
          '// constant/triSurface/*.stl (FreeCAD Rev E export).\n'
          '// Solver settings come from system/au01Parameters.\n')


def foam(cls, obj):
    return 'FoamFile { version 2.0; format ascii; class %s; object %s; }\n' % (cls, obj)


class Case(object):

    def __init__(self, case):
        self._extra = []
        self._gantry_file, self._raised = 'gantry.stl', 0
        self.case = case
        self.sys = os.path.join(case, 'system')
        self.tri = os.path.join(case, 'constant', 'triSurface')
        self.p = read_params(os.path.join(self.sys, 'au01Parameters'))
        with open(os.path.join(self.sys, 'cfd_export_params.json')) as fh:
            self.g = json.load(fh)
        self._geometry()

    @staticmethod
    def _ncells(lo, hi, d):
        """How many cell centres of pitch d fall inside [lo, hi]."""
        first = math.ceil(lo / d - 0.5 - 1e-9)
        last = math.floor(hi / d - 0.5 + 1e-9)
        return max(0, int(last - first + 1))

    @staticmethod
    def _zone_faces(lo, hi, d):
        """The mesh face planes bounding the cells whose centres lie in [lo, hi].

        boxToFace selects by face centre, so a baffle box must straddle a real
        face plane. Centring one on the STL's rack top (1.9799) missed the mesh
        face at 2.000 entirely and selected nothing - a silent no-op that would
        have looked like a completed run with the fix applied.
        """
        first = math.ceil(lo / d - 0.5 - 1e-9)
        last = math.floor(hi / d - 0.5 + 1e-9)
        return first * d, (last + 1) * d

    def f(self, key):
        return float(self.p[key])

    def i(self, key):
        return int(float(self.p[key]))

    # ---- geometry ------------------------------------------------------

    def _geometry(self):
        g, p = self.g, self.p
        s = float(g['scale'])
        room = g['room']
        self.x0, self.x1 = [v * s for v in room['x']]
        self.y0, self.y1 = [v * s for v in room['y']]
        self.eave = room['eave'] * s
        self.apex = room['apex'] * s

        c = self.f('cellSize')
        # y divides exactly; x does not (24.130 is not a multiple of 50 mm), so
        # take the nearest whole number of cells and let the cell be 0.08 %
        # short rather than move the wall off a mesh face.
        self.nx = max(1, int(round((self.x1 - self.x0) / c)))
        self.ny = max(1, int(round((self.y1 - self.y0) / c)))
        self.dx = (self.x1 - self.x0) / self.nx
        self.dy = (self.y1 - self.y0) / self.ny
        # The box top must sit at or above the apex. Keep dz exactly cellSize so
        # the rack tops (2.0) and the bulkhead top (3.0) land on cell faces.
        self.nz = int(math.ceil(self.apex / c - 1e-9))
        self.dz = c
        self.z0, self.z1 = 0.0, self.nz * c

        fw = g['fanwall']
        self.fw_y = [v * s for v in fw['y']]
        self.fw_top = fw['top'] * s
        self.fw_split = fw['module_split'] * s
        self.modules = self.i('modulesPerEnd')
        # west unit discharges +x from its high-x face; east unit discharges -x.
        wx = [v * s for v in fw['w_x']]
        ex = [v * s for v in fw['e_x']]
        self.ends = OrderedDict()
        self.ends['W'] = dict(body=wx, supply_x=wx[1], intake_x=wx[0], sign=+1.0)
        self.ends['E'] = dict(body=ex, supply_x=ex[0], intake_x=ex[1], sign=-1.0)

        self.module_z = []
        for m in range(self.modules):
            self.module_z.append((m * self.fw_split, (m + 1) * self.fw_split))

        # racks straight out of the STL, loads out of the schedule
        solids = stl_solids(os.path.join(self.tri, 'racks_body.stl'))
        sched = g['rack_schedule_kw']
        rows = g['racks']['rows']
        self.racks = []
        for name, b in solids.items():
            tag = name.split('_', 1)[1]                 # A01-HD
            row = tag[0]
            if tag not in sched:
                raise SystemExit('rack %s is not in rack_schedule_kw' % tag)
            iy = rows[row]['intake_y'] * s
            ey = rows[row]['exhaust_y'] * s
            self.racks.append(dict(
                tag=tag, row=row,
                x0=b[0], x1=b[1], y0=b[2], y1=b[3], z0=b[4], z1=b[5],
                intake_y=iy, dir=(1.0 if ey > iy else -1.0),
                kW=float(sched[tag])))
        if len(self.racks) != len(sched):
            raise SystemExit('racks_body.stl has %d solids, schedule has %d'
                             % (len(self.racks), len(sched)))

        # 610 mm pitch on a 50 mm grid is not commensurate, so a rack zone
        # captures 11 or 12 cell columns depending on where it falls. Measure
        # what each zone will actually hold and size its fan from that, or
        # equal-load racks would end up moving unequal air.
        for r in self.racks:
            r['ncx'] = self._ncells(r['x0'] + 0.2 * self.dx,
                                    r['x1'] - 0.2 * self.dx, self.dx)
            r['ncz'] = self._ncells(r['z0'] - 0.2 * self.dz,
                                    r['z1'] - 0.2 * self.dz, self.dz)
            r['area'] = r['ncx'] * self.dx * r['ncz'] * self.dz

        # ---- duty ------------------------------------------------------
        self.Tsup = self.f('supplyTemp_C') + 273.15
        self.rho = P_ATM / (R_AIR * self.Tsup)
        self.dT = self.f('serverDeltaT_K')

        self.mod_area = (self.fw_y[1] - self.fw_y[0]) * (self.fw_top / self.modules)
        # Supply can be throttled below nameplate. With a capped cold side the
        # surplus has nowhere to go: the fan walls move 84.65 kg/s and the racks
        # draw 48.8, and you cannot push the difference through a sealed pod.
        self.throttle = float(self.p.get('supplyThrottle', 1.0))
        q_end = self.f('unitAirflow_m3h') * self.throttle / 3600.0
        self.mod_flow = q_end / self.modules
        self.mod_mdot = self.mod_flow * self.rho
        self.supply_U = self.mod_flow / self.mod_area

        off = self.p.get('unitsOff', 'none').split()
        self.off = set() if off == ['none'] else set(off)
        for tag in self.off:
            if tag[0] not in self.ends or not (1 <= int(tag[1:]) <= self.modules):
                raise SystemExit('unitsOff: %r is not a module (W1 W2 E1 E2)' % tag)

        # Return plenum and pod-end enclosure. Neither exists in the Rev E
        # export; both are generated here as axis-aligned boxes so the option can
        # be tested before it goes back into CAD.
        self.bands = int(float(self.p.get('intakeBands', 4)))
        self.plenumZ = float(self.p.get('plenumFloorZ', 0.0))
        self.deckT = float(self.p.get('plenumDeckThickness', 0.05))
        self.sealPodEnds = self.p.get('sealPodEnds', '0') != '0'

        self.solver = self.p.get('solver', 'buoyantSimpleFoam')
        self.transient = self.solver.endswith('PimpleFoam')

        self.load_kW = sum(r['kW'] for r in self.racks)
        self.demand = self.load_kW * 1000.0 / (CP * self.dT)
        self.supply_kgs = (len(self.ends) * self.modules - len(self.off)) \
            * self.mod_flow * self.rho
        self.cap_kW = self.f('unitCapacity_kW') * len(self.ends) \
            * (1.0 - len(self.off) / float(len(self.ends) * self.modules))

    # ---- helpers -------------------------------------------------------

    def write(self, rel, text):
        path = os.path.join(self.case, rel)
        d = os.path.dirname(path)
        if d and not os.path.isdir(d):
            os.makedirs(d)
        with open(path, 'w') as fh:
            fh.write(text)

    def patches(self):
        """Every generated fan wall patch, in emit order."""
        out = []
        for end in self.ends:
            for m in range(1, self.modules + 1):
                out.append(('supply%s%d' % (end, m), end, m))
        for end in self.ends:
            for m in range(1, self.modules + 1):
                out.append(('intake%s%d' % (end, m), end, m))
        return out

    def live(self, name):
        """Is this patch a working fan wall module?"""
        return name[-2:] not in self.off

    # ---- dictionaries --------------------------------------------------

    def extra_stls(self):
        """Write the solids that are not in the CAD export yet.

        The deck's TOP is flush with the fan wall top, so its thickness eats into
        the cold side rather than into the plenum. Put it the other way up and a
        50 mm deck would cost 0.4 m2 of a 3.6 m2 plenum, because at this height
        we are squeezing into the eave.
        """
        made = []
        if self.plenumZ <= 0:
            return made
        s = float(self.g['scale'])
        hx = [v * s for v in self.g['hac']['x']]
        hy = [v * s for v in self.g['hac']['y']]
        dt = self.g['hac']['door_t'] * s
        xw = self.ends['W']['body'][1]          # west bulkhead plane
        xe = self.ends['E']['body'][0]          # east bulkhead plane
        z0, z1 = self.plenumZ - self.deckT, self.plenumZ

        # Deck over the whole cold side, open only above the hot aisle.
        slabs = [('deck_s', xw, xe, self.y0, hy[0]),
                 ('deck_n', xw, xe, hy[1], self.y1),
                 ('deck_w', xw, hx[0], hy[0], hy[1]),
                 ('deck_e', hx[1], xe, hy[0], hy[1])]
        text = ''.join(box_solid(n, a, b, c, d, z0, z1)
                       for n, a, b, c, d in slabs if b > a and d > c)
        self.write('constant/triSurface/plenum_floor.stl', text)
        made.append(('plenum_floor.stl', 'plenumfloor'))

        if self.sealPodEnds:
            # Close the baffled channel ends from the rack tops up to the deck,
            # so exhaust has to rise into the plenum instead of spilling out of
            # the pod ends into the cold aisles.
            rz = self.racks[0]['z1']
            text = (box_solid('podend_w', hx[0] - dt, hx[0], hy[0], hy[1], rz, z0)
                    + box_solid('podend_e', hx[1], hx[1] + dt, hy[0], hy[1], rz, z0))
            self.write('constant/triSurface/pod_ends.stl', text)
            made.append(('pod_ends.stl', 'podends'))
        return made

    def raise_cross_heads(self):
        """Lift the service-run cross-heads clear of the rack intake faces.

        The export keeps three 200 x 250 mm cross-heads whose underside sits at
        1.810 m - 190 mm BELOW the 2.0 m rack tops - and about 250 mm in front of
        the intake plane. Each is a bluff body parked in the intake path, and the
        three racks they cross carry the three hottest faces in the hall. This
        rewrites them to a stated clearance above the rack tops so the fix can be
        tested; the CAD needs the same change.
        """
        src = os.path.join(self.tri, 'gantry.stl')
        clear = float(self.p.get('crossHeadClearance', 0.0))
        if clear <= 0 or not os.path.exists(src):
            return 'gantry.stl', 0

        tris, cur, head = [], [], None
        for line in open(src, errors='replace'):
            t = line.strip()
            if t.startswith('solid'):
                head = t
            elif t.startswith('vertex'):
                cur.append([float(v) for v in t.split()[1:4]])
                if len(cur) == 3:
                    tris.append(cur); cur = []
        rz = self.racks[0]['z1']

        # cluster the sub-rack-height triangles in x to find the members
        pts = sorted({round(v[0], 3) for tr in tris
                      for v in tr if min(w[2] for w in tr) < rz})
        if not pts:
            return 'gantry.stl', 0
        # Build fresh lists: appending `run` and then clearing it aliases every
        # group to the same emptied list, which silently found one member instead
        # of three.
        groups, run = [], [pts[0]]
        for x in pts[1:]:
            if x - run[-1] < 0.5:
                run.append(x)
            else:
                groups.append(run)
                run = [x]
        groups.append(run)
        spans = [(min(g), max(g)) for g in groups if g]

        # a member's own triangles are the ones inside its x span and below the
        # next tier of services; anything higher is busway or tray and stays put
        moved = 0
        for tr in tris:
            for x0, x1 in spans:
                if all(x0 - 1e-6 <= v[0] <= x1 + 1e-6 for v in tr) \
                        and max(v[2] for v in tr) <= rz + 0.15:
                    dz = (rz + clear) - min(v[2] for v in tr)
                    if dz > 0:
                        for v in tr:
                            v[2] += dz
                        moved += 1
                    break
        out = [(head or 'solid gantry') + '\n']
        for tr in tris:
            out.append('  facet normal 0 0 0\n    outer loop\n')
            for v in tr:
                out.append('      vertex %.6f %.6f %.6f\n' % tuple(v))
            out.append('    endloop\n  endfacet\n')
        out.append('endsolid gantry\n')
        self.write('constant/triSurface/gantry_raised.stl', ''.join(out))
        return 'gantry_raised.stl', moved

    def plenum_area(self):
        """Cross-section available for flow along the hall, above the deck."""
        W = self.y1 - self.y0
        z = self.plenumZ
        if z >= self.apex:
            return 0.0
        if z <= self.eave:
            return W * (self.eave - z) + 0.5 * W * (self.apex - self.eave)
        frac = (self.apex - z) / (self.apex - self.eave)
        return 0.5 * (W * frac) * (self.apex - z)

    def blockMeshDict(self):
        t = [HEADER, foam('dictionary', 'blockMeshDict'), '\nscale 1;\n\nvertices\n(\n']
        for z in (self.z0, self.z1):
            for x, y in ((self.x0, self.y0), (self.x1, self.y0),
                         (self.x1, self.y1), (self.x0, self.y1)):
                t.append('    (%.6f %.6f %.6f)\n' % (x, y, z))
        t.append(');\n\nblocks\n(\n    hex (0 1 2 3 4 5 6 7) (%d %d %d) simpleGrading (1 1 1)\n);\n'
                 % (self.nx, self.ny, self.nz))
        t.append('\nedges ();\n\nboundary\n(\n')
        faces = OrderedDict()
        faces['floor'] = '(0 3 2 1)'
        faces['ceiling'] = '(4 5 6 7)'
        faces['wallW'] = '(0 4 7 3)'
        faces['wallE'] = '(1 2 6 5)'
        faces['wallS'] = '(0 1 5 4)'
        faces['wallN'] = '(3 7 6 2)'
        for n, f in faces.items():
            t.append('    %s { type wall; faces ( %s ); }\n' % (n, f))
        t.append(');\n\nmergePatchPairs ();\n')
        return ''.join(t)

    def snappyHexMeshDict(self):
        lvl = self.i('thinPlateLevel')
        surf = [('roof.stl', 'roof', 0)]
        for end in ('w', 'e'):
            surf.append(('fanwall_%s_body.stl' % end, 'fanwall%s' % end.upper(), 0))
        surf.append(('bulkheads_%s.stl' % self.p['bulkhead'], 'bulkheads', lvl))
        surf.append(('hac.stl', 'hac', lvl))
        if self.p.get('gantry', '1') != '0':
            surf.append((self._gantry_file, 'gantry', lvl))
        for fn, nm in self._extra:
            surf.append((fn, nm, lvl))

        t = [HEADER, foam('dictionary', 'snappyHexMeshDict'),
             '\ncastellatedMesh true;\nsnap true;\naddLayers false;\n\ngeometry\n{\n']
        for fn, nm, _ in surf:
            t.append('    %s { type triSurfaceMesh; name %s; }\n' % (fn, nm))
        t.append('}\n\ncastellatedMeshControls\n{\n')
        t.append('    maxLocalCells 30000000;\n    maxGlobalCells 60000000;\n'
                 '    minRefinementCells 0;\n    nCellsBetweenLevels 2;\n'
                 '    maxLoadUnbalance 0.10;\n    resolveFeatureAngle 45;\n'
                 '    allowFreeStandingZoneFaces true;\n    features ();\n\n'
                 '    refinementSurfaces\n    {\n')
        for _, nm, l in surf:
            t.append('        %s { level (%d %d); patchInfo { type wall; } }\n' % (nm, l, l))
        t.append('    }\n\n    refinementRegions {}\n\n')
        # A point in the south cold aisle, deliberately off every cell face.
        px = self.x0 + 0.5 * (self.x1 - self.x0) + 0.013
        py = self.y0 + 0.5 * (self.racks[0]['intake_y'] - self.y0) + 0.017
        pz = 1.0 + 0.013
        t.append('    locationInMesh (%.4f %.4f %.4f);\n}\n' % (px, py, pz))
        t.append('\nsnapControls\n{\n    nSmoothPatch 3;\n    tolerance 2.0;\n'
                 '    nSolveIter 50;\n    nRelaxIter 5;\n    nFeatureSnapIter 10;\n'
                 '    implicitFeatureSnap true;\n    explicitFeatureSnap false;\n'
                 '    multiRegionFeatureSnap false;\n}\n')
        t.append('\naddLayersControls\n{\n    relativeSizes true;\n    layers {}\n'
                 '    expansionRatio 1.0;\n    finalLayerThickness 0.3;\n'
                 '    minThickness 0.1;\n    nGrow 0;\n    featureAngle 60;\n'
                 '    nRelaxIter 3;\n    nSmoothSurfaceNormals 1;\n'
                 '    nSmoothNormals 3;\n    nSmoothThickness 10;\n'
                 '    maxFaceThicknessRatio 0.5;\n    maxThicknessToMedialRatio 0.3;\n'
                 '    minMedialAxisAngle 90;\n    nBufferCellsNoExtrude 0;\n'
                 '    nLayerIter 50;\n}\n')
        # the shipped meshQualityDict has no errorReduction / nSmoothScale, and
        # snappyHexMesh reads both unconditionally
        t.append('\nmeshQualityControls\n{\n    #includeEtc "caseDicts/meshQualityDict"\n'
                 '    nSmoothScale 4;\n    errorReduction 0.75;\n'
                 '    relaxed { maxNonOrtho 75; }\n}\n')
        t.append('\nwriteFlags ( );\nmergeTolerance 1e-6;\n')
        return ''.join(t)

    def topoSetDict_patches(self):
        """Split the fan wall discharge and return faces off the body patches."""
        ex, ey, ez = 0.4 * self.dx, 0.4 * self.dy, 0.4 * self.dz
        t = [HEADER, foam('dictionary', 'topoSetDict'), '\nactions\n(\n']
        for name, end, m in self.patches():
            e = self.ends[end]
            xc = e['supply_x'] if name.startswith('supply') else e['intake_x']
            zlo, zhi = self.module_z[m - 1]
            t.append('    { name %sFaces; type faceSet; action new; source patchToFace; patch fanwall%s; }\n'
                     % (name, end))
            t.append('    { name %sFaces; type faceSet; action subset; source boxToFace; '
                     'box (%.5f %.5f %.5f) (%.5f %.5f %.5f); }\n'
                     % (name, xc - ex, self.fw_y[0] + ey, zlo + ez,
                        xc + ex, self.fw_y[1] - ey, zhi - ez))
        t.append(');\n')
        return ''.join(t)

    def createPatchDict(self):
        t = [HEADER, foam('dictionary', 'createPatchDict'), '\npointSync false;\n\npatches\n(\n']
        for name, _, _ in self.patches():
            t.append('    { name %s; patchInfo { type patch; } constructFrom set; set %sFaces; }\n'
                     % (name, name))
        t.append(');\n')
        return ''.join(t)

    def topoSetDict_racks(self):
        """Rack cell zones and oriented intake face zones.

        Racks stay as fluid cells rather than solid blockages: the heat and the
        server fans are volume sources, so each rack heats whatever air it
        actually ingests. That is the whole point of the study - a solid rack
        with a fixed exhaust temperature would answer a different question.
        """
        ex, ey, ez = 0.2 * self.dx, 0.2 * self.dy, 0.2 * self.dz
        t = [HEADER, foam('dictionary', 'topoSetDict'), '\nactions\n(\n']
        for r in self.racks:
            tag = r['tag']
            t.append('    { name rackCells_%s; type cellSet; action new; source boxToCell; '
                     'box (%.5f %.5f %.5f) (%.5f %.5f %.5f); }\n'
                     % (tag, r['x0'] + ex, r['y0'] + ey, r['z0'] - ez,
                        r['x1'] - ex, r['y1'] - ey, r['z1'] - ez))
            t.append('    { name rack_%s; type cellZoneSet; action new; source setToCellZone; '
                     'set rackCells_%s; }\n' % (tag, tag))
            iy = r['intake_y']
            t.append('    { name inletFaces_%s; type faceSet; action new; source boxToFace; '
                     'box (%.5f %.5f %.5f) (%.5f %.5f %.5f); }\n'
                     % (tag, r['x0'] + ex, iy - ey, r['z0'] - ez,
                        r['x1'] - ex, iy + ey, r['z1'] - ez))
            # flip true orients the zone normal *into* the rack, so a positive
            # phi sum is air being drawn in. Same convention as case-hall.
            t.append('    { name inlet_%s; type faceZoneSet; action new; source setsToFaceZone; '
                     'faceSet inletFaces_%s; cellSet rackCells_%s; flip true; }\n'
                     % (tag, tag, tag))
            # Split the face into height bands. A whole-face average hides
            # stratification: the end racks run 9 K hotter at one part of the
            # face than the average suggests, and the average cannot say where.
            nb = self.bands
            for b in range(nb):
                zb0 = r['z0'] + (r['z1'] - r['z0']) * b / float(nb)
                zb1 = r['z0'] + (r['z1'] - r['z0']) * (b + 1) / float(nb)
                t.append('    { name inletFaces_%s_b%d; type faceSet; action new; '
                         'source boxToFace; box (%.5f %.5f %.5f) (%.5f %.5f %.5f); }\n'
                         % (tag, b + 1, r['x0'] + ex, iy - ey, zb0 + ez,
                            r['x1'] - ex, iy + ey, zb1 - ez))
                t.append('    { name inlet_%s_b%d; type faceZoneSet; action new; '
                         'source setsToFaceZone; faceSet inletFaces_%s_b%d; '
                         'cellSet rackCells_%s; flip true; }\n'
                         % (tag, b + 1, tag, b + 1, tag))
        t.append(');\n')
        return ''.join(t)

    def topoSetDict_baffles(self):
        """Close the rack tops and the outboard row ends.

        The racks are fluid cellZones so their heat and fans can act on the air
        they actually ingest. The cost is that a cellZone has no walls: without
        these baffles a rack can draw air in over its top, bypassing the intake
        face that every metric is measured on. case-hall had rack-top baffles;
        they were lost when this case moved to snappyHexMesh and dropped
        createBaffles, and the symptom was the top height band drawing a third
        less flow than the other three.
        """
        ex, ey, ez = 0.2 * self.dx, 0.2 * self.dy, 0.2 * self.dz
        t = [HEADER, foam('dictionary', 'topoSetDict'), '\nactions\n(\n']
        first = True
        for row in ('A', 'B'):
            rs = sorted([r for r in self.racks if r['row'] == row],
                        key=lambda r: r['x0'])
            if not rs:
                continue
            y0, y1, z1 = rs[0]['y0'], rs[0]['y1'], rs[0]['z1']
            # snap to the faces that really bound the cell zones
            xw, xe_ = self._zone_faces(rs[0]['x0'] + ex, rs[-1]['x1'] - ex, self.dx)
            _, ztop = self._zone_faces(z1 - ez - 10 * self.dz, z1 - ez, self.dz)
            act = 'new' if first else 'add'
            # rack tops, one box for the whole row
            t.append('    { name rackShellFaces; type faceSet; action %s; source boxToFace; '
                     'box (%.5f %.5f %.5f) (%.5f %.5f %.5f); }\n'
                     % (act, xw + ex, y0 + ey, ztop - ez, xe_ - ex, y1 - ey, ztop + ez))
            first = False
            # outboard row ends - these bound the four racks that are failing
            for xf in (xw, xe_):
                t.append('    { name rackShellFaces; type faceSet; action add; '
                         'source boxToFace; box (%.5f %.5f %.5f) (%.5f %.5f %.5f); }\n'
                         % (xf - ex, y0 + ey, -ez, xf + ex, y1 - ey, ztop - ez))
        t.append('    { name rackShell; type faceZoneSet; action new; source setToFaceZone; '
                 'faceSet rackShellFaces; }\n')
        t.append(');\n')
        return ''.join(t)

