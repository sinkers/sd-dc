    def fvSchemes(self):
        """Schemes tolerant of a cut mesh; ddt switches with the solver.

        Deliberately not case-hall's. That case ran on an orthogonal blockMesh,
        so plain Gauss linear gradients and a corrected laplacian were safe. This
        mesh is cut around the gantry, the gable and 100 mm plates and carries
        skewed cells there; unlimited gradients diverge within ten iterations.
        """
        ddt = 'Euler' if self.transient else 'steadyState'
        t = [HEADER, foam('dictionary', 'fvSchemes'),
             '\nddtSchemes\n{\n    default         %s;\n}\n' % ddt,
             '\ngradSchemes\n{\n    default         cellLimited Gauss linear 1;\n}\n',
             '\ndivSchemes\n{\n    default         none;\n\n']
        # 'bounded' subtracts the continuity error and only belongs in a steady run
        b = '' if self.transient else 'bounded '
        for term, sch in (('div(phi,U)', 'limitedLinearV 1'),
                          ('div(phi,K)', 'limitedLinear 1'),
                          ('div(phi,h)', 'limitedLinear 1'),
                          ('div(phi,e)', 'limitedLinear 1'),
                          ('div(phi,Ekp)', 'limitedLinear 1'),
                          ('div(phi,k)', 'limitedLinear 1'),
                          ('div(phi,omega)', 'limitedLinear 1'),
                          ('div(phid,p)', 'limitedLinear 1')):
            t.append('    %-16s %sGauss %s;\n' % (term, b, sch))
        t.append('    div(((rho*nuEff)*dev2(T(grad(U))))) Gauss linear;\n}\n')
        t.append('\nlaplacianSchemes\n{\n    default         Gauss linear limited corrected 0.33;\n}\n')
        t.append('\ninterpolationSchemes\n{\n    default         linear;\n}\n')
        t.append('\nsnGradSchemes\n{\n    default         limited corrected 0.33;\n}\n')
        t.append('\nwallDist\n{\n    method          meshWave;\n}\n')
        return ''.join(t)

    def fvSolution(self):
        """GAMG is tuned explicitly: on this cut mesh the defaults coarsen far
        enough to hit a degenerate level and die inside GAMGSolver::scale with a
        floating point exception that looks nothing like a physics problem."""
        gamg = ('        solver          GAMG;\n        smoother        GaussSeidel;\n'
                '        tolerance       1e-7;\n        relTol          0.01;\n'
                '        cacheAgglomeration true;\n        agglomerator    faceAreaPair;\n'
                '        nCellsInCoarsestLevel 500;\n        mergeLevels     1;\n'
                '        nPreSweeps      0;\n        nPostSweeps     2;\n')
        t = [HEADER, foam('dictionary', 'fvSolution'), '\nsolvers\n{\n']
        t.append('    p_rgh\n    {\n%s    }\n' % gamg)
        if self.transient:
            t.append('\n    p_rghFinal\n    {\n        $p_rgh;\n        relTol          0;\n    }\n')
        t.append('\n    "(U|h|e|k|omega)"\n    {\n        solver          PBiCGStab;\n'
                 '        preconditioner  DILU;\n        tolerance       1e-7;\n'
                 '        relTol          0.1;\n    }\n')
        if self.transient:
            t.append('\n    "(U|h|e|k|omega)Final"\n    {\n        $U;\n'
                     '        relTol          0;\n    }\n')
            t.append('\n    "(rho|rhoFinal)"\n    {\n        solver          PCG;\n'
                     '        preconditioner  DIC;\n        tolerance       1e-7;\n'
                     '        relTol          0;\n    }\n')
        t.append('}\n')
        if self.transient:
            # Every boundary prescribes a flow rate, so there is no pressure
            # outlet anywhere and p_rgh needs an explicit reference.
            t.append('\nPIMPLE\n{\n    momentumPredictor yes;\n    nOuterCorrectors 2;\n'
                     '    nCorrectors     1;\n    nNonOrthogonalCorrectors 0;\n'
                     '    pRefCell        0;\n    pRefValue       %g;\n}\n' % P_ATM)
            t.append('\nrelaxationFactors\n{\n    fields\n    {\n        p_rgh 0.7;\n'
                     '        "p_rghFinal" 1;\n    }\n    equations\n    {\n'
                     '        "(U|h|k|omega)" 0.8;\n        ".*Final" 1;\n    }\n}\n')
        else:
            t.append('\nSIMPLE\n{\n    nNonOrthogonalCorrectors 0;\n    pRefCell        0;\n'
                     '    pRefValue       %g;\n\n    residualControl\n    {\n'
                     '        p_rgh           1e-4;\n        U               1e-4;\n'
                     '        h               1e-4;\n        "(k|omega)"     1e-3;\n'
                     '    }\n}\n' % P_ATM)
            t.append('\nrelaxationFactors\n{\n    fields\n    {\n        rho             1.0;\n'
                     '        p_rgh           0.3;\n    }\n    equations\n    {\n'
                     '        U               0.5;\n        h               0.4;\n'
                     '        "(k|omega)"     0.4;\n    }\n}\n')
        return ''.join(t)

